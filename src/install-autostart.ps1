# Makes the redaction proxy start at logon.
#
# This script does NOT touch ~/.claude/settings.json. Wiring ANTHROPIC_BASE_URL
# and the SessionStart liveness hook is a separate, deliberate step -- it points
# all of your API traffic at this process, so it must never be a side effect of
# running an installer.
#
# The proxy must already be listening before Claude Code starts: the base URL is
# read at startup and the first request follows within seconds, so it cannot be
# started on demand.
#
# Method: a .vbs launcher in the per-user Startup folder.
#   - needs no administrator rights (Register-ScheduledTask does, and fails with
#     "Access is denied" on a standard account)
#   - launches node with window style 0, so no console window appears at logon
#
# Trade-off vs a scheduled task: no automatic restart if the proxy crashes. The
# SessionStart liveness hook covers that case -- it tells you loudly, at the top
# of the next session, that redaction is not active. If you want restart-on-
# failure as well, run this from an elevated prompt:
#
#   $n=(Get-Command node).Source; $s='<repo>\proxy\start.js'
#   Register-ScheduledTask -TaskName ClaudeRedactionProxy `
#     -Action (New-ScheduledTaskAction -Execute $n -Argument "`"$s`"") `
#     -Trigger (New-ScheduledTaskTrigger -AtLogOn) `
#     -Settings (New-ScheduledTaskSettingsSet -Hidden -RestartCount 3 `
#                 -RestartInterval (New-TimeSpan -Minutes 1)) -Force
#
# Usage:  powershell -ExecutionPolicy Bypass -File proxy/install-autostart.ps1
# Remove: delete the .vbs path this script prints.

$ErrorActionPreference = 'Stop'

$startScript = Join-Path $PSScriptRoot 'start.js'
if (-not (Test-Path $startScript)) {
  Write-Error "start.js not found at $startScript"
  exit 1
}

$node = (Get-Command node -ErrorAction SilentlyContinue).Source
if (-not $node) {
  Write-Error 'node not found on PATH'
  exit 1
}

$startupDir = [Environment]::GetFolderPath('Startup')
$vbsPath = Join-Path $startupDir 'claude-redaction-proxy.vbs'

# Window style 0 = hidden; False = do not wait for the process to exit.
$vbs = @"
' Starts the Claude Code redaction proxy at logon, with no console window.
' Generated by proxy/install-autostart.ps1 -- safe to delete to disable.
Set sh = CreateObject("WScript.Shell")
sh.CurrentDirectory = "$PSScriptRoot"
sh.Run """$node"" ""$startScript""", 0, False
"@

Set-Content -Path $vbsPath -Value $vbs -Encoding ASCII

if (Test-Path $vbsPath) {
  Write-Host "Installed logon launcher:"
  Write-Host "  $vbsPath"
  Write-Host "Runs hidden: $node `"$startScript`""
  Write-Host ''
  Write-Host 'This only STARTS the proxy. It does NOT route Claude Code through it.'
  Write-Host 'That requires ANTHROPIC_BASE_URL in ~/.claude/settings.json.'
} else {
  Write-Error "Failed to write $vbsPath"
  exit 1
}
